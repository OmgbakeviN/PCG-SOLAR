// Neon Object Storage: credentials injected server-side into Neon Functions.
// Never import this file into the Vite/React bundle.
import { AwsClient } from 'aws4fetch'

const BUCKET = 'product-images'
const regionFromEndpoint = (value: string) => value.match(/\.(us-east-2|eu-central-1)\.aws\.neon\.tech/i)?.[1]

function settings() {
  const base = process.env.AWS_ENDPOINT_URL_S3?.replace(/\/+$/, '')
  const accessKeyId = process.env.AWS_ACCESS_KEY_ID
  const secretAccessKey = process.env.AWS_SECRET_ACCESS_KEY
  if (!base || !accessKeyId || !secretAccessKey) {
    throw new Error('Neon Object Storage environment is missing on the Function branch')
  }
  const region = regionFromEndpoint(base) || process.env.AWS_REGION || 'us-east-2'
  return { base, accessKeyId, secretAccessKey, region }
}

function urlForKey(base: string, key: string) {
  // Every part of the key is generated by our backend; encode as a URL path safely.
  return `${base}/${BUCKET}/${key.split('/').map(encodeURIComponent).join('/')}`
}

export function publicImageUrl(key: unknown) {
  if (typeof key !== 'string' || !/^products\/[1-9]\d*\/[a-f\d-]{36}\.(?:jpg|png|webp)$/i.test(key)) return null
  const base = process.env.AWS_ENDPOINT_URL_S3?.replace(/\/+$/, '')
  return base ? urlForKey(base, key) : null
}

function s3Client() {
  const config = settings()
  return {
    aws: new AwsClient({
      accessKeyId: config.accessKeyId,
      secretAccessKey: config.secretAccessKey,
      service: 's3',
      region: config.region,
    }),
    url: (key: string) => urlForKey(config.base, key),
  }
}

export async function putImage(key: string, data: Uint8Array, contentType: string) {
  const { aws, url } = s3Client()
  const response = await aws.fetch(url(key), {
    method: 'PUT',
    body: data,
    headers: {
      'Content-Type': contentType,
      // Unique UUID object keys mean no stale cache on image updates.
      'Cache-Control': 'public, max-age=31536000, immutable',
    },
  })
  if (!response.ok) throw new Error(`Neon storage upload failed (${response.status})`)
}

export async function deleteImage(key: string) {
  const { aws, url } = s3Client()
  const response = await aws.fetch(url(key), { method: 'DELETE' })
  if (!response.ok && response.status !== 404) throw new Error(`Neon storage deletion failed (${response.status})`)
}
